export const tApp = (key: string, lang: 'en' | 'ar'): string => {
  if (!key) return '';
  if (lang === 'ar') {
    if (appArDict[key]) return appArDict[key];

    // Check if key is a composite text with service names, e.g. "Apron x2, Children Fancy Dress x2"
    let translated = String(key);
    Object.keys(appArDict).forEach((k) => {
      if (appArDict[k] && translated.includes(k)) {
        translated = translated.split(k).join(appArDict[k]);
      }
    });
    return translated;
  }
  return key;
};
